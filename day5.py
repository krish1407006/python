# string examples
a = "hello world"
print(a)  # This will print the string "hello world"    

b = """This is a multi-line string.
 It can span multiple lines."""
print(b)  # This will print the multi-line string
print(a[2])
print(a[0:5])  # This will print the substring "hello"

for character in a:
    print (character)  # This will print each character in the string 'a' on a new line
    