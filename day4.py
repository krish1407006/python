# type casting example
# In this example, we have two string variables 'a' and 'b'. We will first concatenate them as strings and then convert them to integers to perform addition.
a = "1"
b = " 12"
print(a + b)  # This will concatenate the two strings, resulting in "1 12"
print(int(a) + int(b))  # This will convert the strings to integers and then add them, resulting in 13

